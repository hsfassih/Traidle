def reason(text):
    t = text.lower()
    if "news" in t or "economic calendar" in t:
        return "needs an economic calendar (`external.news_event`), not stored"
    if "account risk" in t or "multiple pairs" in t or "re-entry" in t or "breakeven" in t:
        return "needs trade / portfolio state, not stored"
    if any(k in t for k in ("beginner", "stick to", "rely consistently", "convince yourself", "ego", "not always the highest", "build confidence")):
        return "trader-discipline statement, not a market condition"
    if any(k in t for k in ("dax", "forex pairs", "indices have")):
        return "instrument / market selection; Traidle runs one symbol and stores no instrument metadata"
    if "timeframe" in t and ("entry" in t or "scale" in t):
        return "timeframe-selection guidance (covered by `timeframes.notes`), not a candle condition"
    if "higher timeframe" in t or "higher-timeframe" in t or "htf" in t or "narrative" in t or "bias" in t:
        return "needs the presenter's discretionary higher-timeframe narrative; no numeric rule is given"
    if "risk-to-reward" in t:
        return "needs a structured entry/stop/target pair; the presenter gives none"
    if "friday" in t or "thursday" in t or "monday" in t or "monthly" in t or "weekly template" in t:
        return "day/week expectancy heuristic; no threshold given"
    return "qualitative judgement; the presenter gives no threshold, so any number would be invented"


